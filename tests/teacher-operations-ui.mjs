import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFile} from 'node:fs/promises';
import path from 'node:path';

const base=process.env.TEST_URL||'http://127.0.0.1:8787';
assert(new URL(base).hostname==='127.0.0.1'&&process.env.TEST_DB&&path.resolve(process.env.TEST_DB).startsWith(path.resolve('test-output')+path.sep),'Use an isolated local test database');
const {chromium}=createRequire(import.meta.url)('C:/Users/경남교육청/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const setup=(await readFile('private/teacher-setup.txt','utf8')).trim();
const created=await fetch(base+'/api/create',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({setupKey:setup,size:2})});
assert.equal(created.status,201);
const room=await created.json();
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage(),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto(base+'/teacher');
 await page.locator('#teacherRoom').fill(room.roomCode);
 await page.locator('#teacherCode').fill(room.teacherKey);
 await page.locator('#joinTeacher').click();
 await page.locator('#teacherDashboard:not([hidden])').waitFor();
 assert.match(await page.locator('#teacherRoster').innerText(),/학생 001/);
 assert.match(await page.locator('#teacherRoster').innerText(),/학생 002/);
 await page.locator('#roomDay').fill('2');
 await page.locator('#roomWeather').selectOption('3');
 await page.locator('#roomMarket').selectOption('1');
 await page.locator('#roomPhase').selectOption('협력');
 await page.locator('#saveRoom').click();
 await page.waitForFunction(()=>document.querySelector('#teacherStatus')?.textContent?.includes('적용'));
 const current=await fetch(base+'/api/state',{headers:{authorization:'Bearer '+room.students[0].code}}).then(r=>r.json());
 assert.equal(current.room.day,2);
 assert.equal(current.room.weather,3);
 assert.equal(current.room.market,true);
 assert.equal(current.room.phase,'협력');
 const download=page.waitForEvent('download');
 await page.locator('#exportProgress').click();
 assert.match((await download).suggestedFilename(),/활동현황\.csv$/);
 await page.locator('#roomDay').fill('3');
 await page.locator('#roomWeather').selectOption('0');
 await page.locator('#roomMarket').selectOption('0');
 await page.locator('#saveRoom').click();
 await page.waitForFunction(()=>document.querySelector('#roomDay')?.value==='3'&&document.querySelector('#roomMarket')?.value==='0');
 const closed=await fetch(base+'/api/state',{headers:{authorization:'Bearer '+room.students[1].code}}).then(r=>r.json());
 assert.equal(closed.room.day,3);
 assert.equal(closed.room.weather,0);
 assert.equal(closed.room.market,false);
 assert.deepEqual(errors,[]);
 console.log('PASS: teacher roster, day/weather/market/phase changes reach students, and progress CSV downloads');
}finally{await browser.close()}
